func writeNetworkFixture(t *testing.T, name, content string) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), name)
	if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
		t.Fatalf("write fixture %s: %v", name, err)
	}
	return path
}

// The kernel lists every field twice in /proc/net/snmp: the first block names
// them, the second gives the values. A parser that reads only one of the two
// blocks reports zeros for everything.
func TestParseProcNetSNMP(t *testing.T) {
	path := writeNetworkFixture(t, "snmp", `Tcp: RtoAlgorithm RtoMin RtoMax MaxConn ActiveOpens PassiveOpens AttemptFails EstabResets CurrEstab InSegs OutSegs RetransSegs InErrs OutRsts
Tcp: 1 200 120000 -1 12 34 5 6 7 1000 2000 3 4 5
Udp: InDatagrams NoPorts InErrors OutDatagrams RcvbufErrors SndbufErrors
Udp: 10 1 2 20 3 4
`)

	tcp, udp, ok := parseProcNetSNMP(path)
	if !ok {
		t.Fatal("parseProcNetSNMP reported no TCP section")
	}
	if tcp.ActiveOpens != 12 || tcp.PassiveOpens != 34 {
		t.Errorf("opens = %d/%d, want 12/34", tcp.ActiveOpens, tcp.PassiveOpens)
	}
	if tcp.CurrEstab != 7 {
		t.Errorf("curr_estab = %d, want 7", tcp.CurrEstab)
	}
	if tcp.RetransSegs != 3 {
		t.Errorf("retrans_segs = %d, want 3", tcp.RetransSegs)
	}
	if tcp.RetransPercent < 0.14 || tcp.RetransPercent > 0.16 {
		t.Errorf("retrans_percent = %v, want about 0.15", tcp.RetransPercent)
	}
	if udp.InDatagrams != 10 || udp.SndbufErrors != 4 {
		t.Errorf("udp = %+v, want 10 datagrams and 4 send buffer errors", udp)
	}
}

// A missing file must not look like a healthy stack: the caller has to be
// able to tell "no data" from "zero errors".
func TestParseProcNetSNPMissingFile(t *testing.T) {
	_, _, ok := parseProcNetSNMP(filepath.Join(t.TempDir(), "missing"))
	if ok {
		t.Error("parseProcNetSNMP accepted a missing file")
	}
}

func TestReadResolvConfFrom(t *testing.T) {
	path := writeNetworkFixture(t, "resolv.conf", `# generated by systemd-resolved
nameserver 127.0.0.53
nameserver 1.1.1.1
search lan example.home
options edns0
`)

	dns, search := readResolvConfFrom(path)
	if len(dns) != 2 || dns[0] != "127.0.0.53" || dns[1] != "1.1.1.1" {
		t.Errorf("dns = %v, want the two resolvers", dns)
	}
	if len(search) != 2 || search[0] != "lan" {
		t.Errorf("search = %v, want the two domains", search)
	}
}

// The addresses in /proc/net/route are little-endian hex. Reading them as
// big-endian sends every route to the wrong network.
func TestReadIPv4Routes(t *testing.T) {
	path := writeNetworkFixture(t, "route", `Iface	Destination	Gateway 	Flags	RefCnt	Use	Metric	Mask		MTU	Window	IRTT
enp3s0	00000000	0102A8C0	0003	0	0	100	00000000	0	0	0
enp3s0	0002A8C0	00000000	0001	0	0	100	00FFFFFF	0	0	0
`)

	routes := readIPv4Routes(path)
	if len(routes) != 2 {
		t.Fatalf("routes = %d, want 2", len(routes))
	}
	if routes[0].Kind != "default" || routes[0].Gateway != "192.168.2.1" {
		t.Errorf("default route = %+v, want 192.168.2.1", routes[0])
	}
	if routes[0].Interface != "enp3s0" || routes[0].Metric != 100 {
		t.Errorf("default route lost its interface or metric: %+v", routes[0])
	}
	if routes[1].Kind != "network" || routes[1].Destination != "192.168.2.0" {
		t.Errorf("network route = %+v, want 192.168.2.0", routes[1])
	}
}

func TestReadARPNeighbors(t *testing.T) {
	path := writeNetworkFixture(t, "arp", `IP address       HW type     Flags       HW address            Mask     Device
192.168.2.10     0x1         0x2         aa:bb:cc:dd:ee:ff     *        enp3s0
192.168.2.11     0x1         0x0         00:00:00:00:00:00     *        enp3s0
`)

	neighbors := readARPNeighbors(path)
	if len(neighbors) != 1 {
		t.Fatalf("neighbors = %d, want 1 (the unresolved entry must be dropped)", len(neighbors))
	}
	if neighbors[0].IP != "192.168.2.10" || neighbors[0].MAC != "aa:bb:cc:dd:ee:ff" {
		t.Errorf("neighbor = %+v, want the reachable host", neighbors[0])
	}
	if neighbors[0].State != "reachable" {
		t.Errorf("state = %q, want reachable", neighbors[0].State)
	}
	if neighbors[0].Interface != "enp3s0" {
		t.Errorf("interface = %q, want enp3s0", neighbors[0].Interface)
	}
}

func TestReadWirelessFrom(t *testing.T) {
	path := writeNetworkFixture(t, "wireless", `Inter-| sta-|   Quality        |   Discarded packets               | Missed | WE
 face | tus | link level noise |  nwid  crypt   frag  mismatch   |  wlan  | 22
  wlan0: 0000   70.  -50.  -256        0      0      0      0        0
`)

	links := readWirelessFrom(path)
	if len(links) != 1 {
		t.Fatalf("links = %d, want 1", len(links))
	}
	link := links[0]
	if link.Interface != "wlan0" {
		t.Errorf("interface = %q, want wlan0", link.Interface)
	}
	if link.SignalDBM != -50 || link.Quality != 70 || link.NoiseDBM != -256 {
		t.Errorf("wireless = %+v, want -50 dBm, quality 70, noise -256", link)
	}
}

